# Дано трехзначное число. Проверить истинность высказывания: «Все цифры данного числа различны».
n = input("Введите трехзначное число: ")
while True:
    try:
        n = int(n)
        break
    except ValueError:
        n = input("Ошибка! Введите ЧИСЛО: ")

n = abs(n)

a = n // 100
b = n // 10 % 10
c = n % 10

print(a != b and a != c and b != c)