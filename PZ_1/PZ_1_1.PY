# Дано трехзначное число. Вывести число, полученное при перестановке цифр десятков и единиц исходного числа.
a = input("Введите трехзначное число: ")
while True:
    try:
        a = int(a)
        break
    except ValueError:
        a = input("Ошибка! Введите ТРЕХЗНАЧНОЕ число: ")

if 100 <= int(a) <= 999:

    b = a // 100
    c = a // 10 % 10
    d = a % 10

    print("Число после перестановки:", b * 100 + d * 10 + c)

else:
    print("Ошибка! Число должно быть трехзначным.")
